def load(n):
    return json.load(open(os.path.join(TAX, n), encoding='utf-8'))


def main():
    dry = '--dry' in sys.argv
    inv, tags, comps = load('inventory.json'), load('leaf_tags.json'), load('components.json')
    stages, c2l = load('stages.json'), load('comp2l1.json')
    if 'S11' in inv['l1']:
        sys.exit('S11 已存在，本脚本只跑一次')

    inv['l1']['S11'] = {'name': '图表与可视化',
                        'definition': '把数据落成图：选图型、写渲染 spec、执行渲染、挂进正文。'
                                      '失效多为 spec 不合契约、序列缺项、数值/换算错、图没渲染或引用挂不上。'}
    inv['l1']['S12'] = {'name': '任务编排',
                        'definition': '决定做几步、按什么顺序、要不要先补前置（技能流程、基期、核对）。'
                                      '不是取数查询设计，也不是检索词构造。'}
    stages['S11'] = dict(inv['l1']['S11'], components=['display'])
    stages['S12'] = dict(inv['l1']['S12'], components=['任务规划'])

    for mei_prefix, rows, l1 in (('S11', CHART, 'S11'), ('S12', ORCH, 'S12')):
        seq = collections.Counter()
        for mei, name, tg, definition, include, exclude, plain in rows:
            seq[mei] += 1
            nid = f'{l1}.{mei}.{seq[mei]}'
            inv['nodes'].append({'id': nid, 'l1': l1, 'l2': mei, 'name': name,
                                 'definition': definition + f'（本叶仅收{l1}段产生的缺陷）',
                                 'include': include, 'exclude': exclude,
                                 'components': ['display'] if l1 == 'S11' else ['任务规划'],
                                 'plain': plain})
            tags[nid] = tg

    # 组件 → 新阶段：图表族全部落 S11；泛规划落 S12
    comps['规划'] = {'tool': '任务规划', 'label': '任务编排模型', 'role': 'planning', 'stage': 'S12'}
    for raw, e in comps.items():
        if e['tool'] == 'display' or 'visualizer' in raw:
            e['stage'] = 'S11'
        elif e['tool'] == '任务规划':
            e['stage'] = 'S12'
        elif e.get('role') == 'request_generation':
            e['stage'] = 'S10'
        else:
            base = [s for s in str(c2l.get(e['tool'], 'S3')).split('+') if s not in ('S10', 'S11', 'S12')]
            e['stage'] = base[0] if base else 'S3'
    span = collections.defaultdict(set)
    for raw, e in comps.items():
        span[e['tool']].add(e['stage'])
    for t, st in span.items():
        c2l[t] = '+'.join(sorted(st, key=lambda x: int(x[1:]))) if len(st) > 1 else next(iter(st))
    c2l['任务规划'] = 'S12'

    print(f"新增 S11 {len(CHART)} 叶、S12 {len(ORCH)} 叶；总段数 {len(inv['l1'])}，总叶子 {len(inv['nodes'])}")
    dist = collections.Counter(e['stage'] for e in comps.values())
    print('组件落段:', dict(sorted(dist.items(), key=lambda kv: int(kv[0][1:]))))
    if dry:
        print('dry run')
        return
    for name, obj in [('inventory.json', inv), ('leaf_tags.json', tags),
                      ('stages.json', stages), ('comp2l1.json', c2l), ('components.json', comps)]:
        json.dump(obj, open(os.path.join(TAX, name), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('written')


if __name__ == '__main__':
    main()
